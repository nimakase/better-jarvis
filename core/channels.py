"""
core/channels.py — 渠道能力画像（自我处境感知 ㉒）

问题：传输层早就分渠道了（web 卡片 vs 飞书消息 vs 后台无人看），
但大脑（controller）此前拿不到「我这轮从哪个渠道来」——渠道差异憋在
传输层，模型只能靠 system prompt 里几句硬编码先验。

本模块给每个渠道一份【能力画像】，由 controller 按本轮实际渠道注入
system prompt，让模型自觉调整表达与行为：
  - 飞书：卡片渲染，宽表会挤成一坨 → 表格落文件发送；
  - 网页：富 Markdown + 交互卡片，尽管用；
  - 后台：没有人在看 → 绝不提问、绝不等确认，直接完成并交付。

进 system prompt = 提示词注入面 → 本模块 PROTECTED。
"""
from __future__ import annotations

# 渠道 -> 画像（注入 system prompt 的一句话能力说明）
PROFILES: dict[str, str] = {
    "web": (
        "当前渠道：自制网页（PWA）。支持富 Markdown、表格、交互卡片（文件下载/"
        "证件揭示/代码审查），流式渲染。表达不受限；文件用 send_file_to_chat 出卡片。"
    ),
    "lark": (
        "当前渠道：飞书。卡片渲染，支持富文本、可点击按钮与结构化表单。请按内容"
        "自行挑选最合适的表达形态，别一律只回纯文字：\n"
        "  · 普通回答 → 直接回文字（会自动渲染成富文本卡，支持 Markdown）。\n"
        "  · 【要用户做选择/确认/选下一步】（是否、方案A/B、激活/修改/放弃等）→ 调"
        " send_choice_buttons 给按钮，别让用户打字；正文只写一句引导语，选项放工具里。\n"
        "  · 【需要用户提供多个字段】（新建日历事件的标题/时间/地点等）→ 调"
        " send_input_form 发一张表单一次收齐，别来回追问。\n"
        "  · 宽表格（≥4 列）会挤坏 → 生成文件发送而非贴表格；文件/图片可直接发消息。\n"
        "  · 用户发来的图片/文件已被自动存到本机并在消息里给出路径，可据此处理"
        "（如识别证件、读入文档）。长内容宜分段。"
    ),
    "background": (
        "当前渠道：后台运行（定时任务/工作流/子 agent），【没有人在看】。"
        "绝不提问、绝不等待确认、绝不说「需要我……吗」；直接完成本职任务并输出结果，"
        "交付走投递渠道。"
    ),
}

_FALLBACK = "当前渠道：未知。按保守表达（避免宽表格与依赖交互的输出）。"


def note(channel: str) -> str:
    """渠道画像注入块。"""
    return "【渠道感知】" + PROFILES.get(channel or "", _FALLBACK)


def known_channels() -> list[str]:
    return list(PROFILES)
